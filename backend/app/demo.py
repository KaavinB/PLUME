def seed_demo(session: Session) -> dict[str, Any]:
    settings = get_settings()
    chain: ChainClient | None
    try:
        chain = get_chain(settings)
    except ChainError:
        chain = None
    created = []
    for p in PERSONAS:
        wallet = chain.account(p["hd_index"]).address if (chain and p["hd_index"] is not None) else None
        user = session.get(User, p["id"])
        if user is None:
            user = User(**p, wallet_address=wallet, is_demo=True)
            session.add(user)
            created.append(p["id"])
        else:
            user.wallet_address = wallet
            user.hd_index = p["hd_index"]
    session.commit()

    approvals: list[str] = []
    if chain is not None:
        for p in PERSONAS:
            if p["id"] == "provider" and not chain.is_approved_provider(chain.account(2).address):
                chain.transact(0, "setProviderApproval", chain.account(2).address, True)
                approvals.append("provider")
            if p["id"] == "verifier" and not chain.is_approved_verifier(chain.account(3).address):
                chain.transact(0, "setVerifierApproval", chain.account(3).address, True)
                approvals.append("verifier")
    return {
        "personas_created": created,
        "onchain_approvals_sent": approvals,
        "chain_connected": chain is not None,
    }


def _deleted(session: Session, stmt: Any) -> int:
    return int(cast(CursorResult[Any], session.execute(stmt)).rowcount)


def reset_demo(session: Session) -> dict[str, Any]:
    """Remove all repair-workflow and investigation state. Observations and incidents are kept."""
    settings = get_settings()
    counts = {}
    for model in (ImpactReceipt, Verification, Evidence):
        counts[model.__tablename__] = _deleted(session, delete(model))
    counts["chain_events"] = _deleted(session, delete(ChainEvent))
    counts["audit_events"] = _deleted(session, delete(AuditEvent))
    counts["repair_projects"] = _deleted(session, delete(RepairProject))
    counts["investigations"] = _deleted(session, delete(Investigation))
    session.execute(update(Incident).where(Incident.status != "open").values(status="open"))
    session.commit()
    shutil.rmtree(settings.evidence_dir, ignore_errors=True)
    return {"deleted": counts}


def advance_chain_time(chain: ChainClient, days: float) -> dict[str, Any]:
    """Local Anvil only: advance block time to simulate elapsed field work and monitoring."""
    if chain.chain_id != 31337:
        raise ChainError("time travel is only available on the local Anvil chain")
    before = chain.latest_timestamp()
    chain.w3.provider.make_request("evm_increaseTime", [int(days * 86400)])  # type: ignore[arg-type]
    chain.w3.provider.make_request("evm_mine", [])  # type: ignore[arg-type]
    after = chain.latest_timestamp()
    return {
        "chain_time_before": datetime.fromtimestamp(before, UTC).isoformat(),
        "chain_time_after": datetime.fromtimestamp(after, UTC).isoformat(),
    }


